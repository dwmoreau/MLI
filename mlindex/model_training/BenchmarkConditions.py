BY_KEY = {condition.key: condition for condition in CONDITIONS}
BY_TAG = {condition.tag: condition for condition in CONDITIONS}
BUNDLE_LABELS = {condition.tag: condition.label for condition in CONDITIONS}

# The sparsity rungs, ascending, because the nesting is implemented by drawing the holes once at
# the largest rung and taking prefixes -- which is what "prefix" means here. The nesting lives in
# the peak-list preparation, not in this table.
SPARSITY_LADDER = tuple(sorted(
    condition.n_dropout for condition in CONDITIONS if condition.axis == 'sparsity'))
MAX_NESTED_DROPOUT = max(SPARSITY_LADDER) if SPARSITY_LADDER else 0

# The severe end of each axis. Membership is a per-condition flag rather than a rule over axes, so
# adding a mild bundle to an axis that already has a severe one cannot enlarge the hard population
# by accident.
HARD_BUNDLES = tuple(condition.tag for condition in CONDITIONS if condition.is_hard)


def tags():
    return tuple(condition.tag for condition in CONDITIONS)


def condition_row(condition):
    """One flat record per bundle, for the condition table shipped as an artefact."""
    return {
        'key': condition.key,
        'label': condition.label,
        'tag': condition.tag,
        'axis': condition.axis,
        'error_law': ERROR_LAW,
        'error_multiplier': condition.error_multiplier,
        'intercept_scale': condition.intercept_scale,
        'n_contaminants': condition.n_contaminants,
        'n_dropout': condition.n_dropout,
        'second_phase_lines': condition.second_phase_lines,
        'second_phase_bias': condition.second_phase_bias,
        'is_hard': condition.is_hard,
        'description': condition.description,
        }


def condition_set_digest():
    """A digest of the whole table, written into every manifest.

    Two arms are only paired if this matches. A description is part of the digest deliberately:
    it is cheap to keep stable, and a table that has been edited at all is worth re-reading before
    its numbers are compared with another run's.
    """
    payload = json.dumps([condition_row(condition) for condition in CONDITIONS],
                         sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(payload.encode('utf-8')).hexdigest()
