def records_to_frame(records):
    """One frame from the recorder's per-(pattern, lattice) column dicts.

    A record holds arrays for the per-candidate columns and plain values for the ones that
    describe the whole block; the plain ones are broadcast here rather than at the point they are
    recorded, where a triclinic pattern would mean several thousand copies of the same string.
    """
    frames = []
    for record in records:
        n_rows = record['M20'].shape[0]
        columns = {}
        for name, value in record.items():
            if isinstance(value, np.ndarray):
                columns[name] = list(value) if value.ndim > 1 else value
            elif isinstance(value, list):
                columns[name] = value
            else:
                columns[name] = [value]*n_rows
        frames.append(pd.DataFrame(columns))
    if not frames:
        return pd.DataFrame(columns=list(CANDIDATE_COLUMNS))
    return pd.concat(frames, ignore_index=True)


def label_frame(candidates, entries, rtol=1e-2):
    """Attach `is_correct` and `is_off_by_two`, which need truth the recorder cannot see.

    Labels are attached at generation, before anything else reads the frame: the question every
    reported number rests on is whether a candidate cell *is* the true cell, allowing for
    reindexing and for sub- and super-cells, and it is not recoverable from a stored pool that
    does not carry it.

    Batched per (pattern, lattice system). The scalar `validate_candidate_known_bl` costs
    milliseconds a candidate against pools of millions, so it is not an option here; the batch
    form is gated against it on all seven lattice systems in
    `tests/test_candidate_validation_batch.py`.
    """
    from mlindex.optimization.CandidateValidation import label_known_bl_batch
    from mlindex.utilities.UnitCellTools import get_partial_unit_cell

    result = candidates.copy()
    n_rows = result.shape[0]
    is_correct = np.zeros(n_rows, dtype=bool)
    is_off_by_two = np.zeros(n_rows, dtype=bool)
    if n_rows:
        truth = entries.drop_duplicates('entry_id').set_index('entry_id')
        missing = sorted(set(result['entry_id']) - set(truth.index))
        if missing:
            raise ValueError(
                f'{len(missing)} candidate entry_id(s) have no row in the entry table, first '
                f'{missing[:3]}. Labelling them would leave the correctness column false for a '
                'reason that has nothing to do with the cells.')
        for (entry_id, lattice_system), group in result.groupby(
                ['entry_id', 'lattice_system'], sort=False):
            positions = result.index.get_indexer(group.index)
            unit_cell_true = np.asarray(truth.loc[entry_id, 'unit_cell_true'], dtype=np.float64)
            partial_true = get_partial_unit_cell(unit_cell_true, lattice_system=lattice_system)
            # Stacked per group and never over the whole frame: a candidate's cell is the partial
            # cell for its own lattice system, one number for cubic and six for triclinic, and a
            # pool holds all fourteen lattices.
            predicted = np.stack([np.asarray(cell, dtype=np.float64)
                                  for cell in group['unit_cell']])
            if predicted.shape[1] != len(partial_true):
                raise ValueError(
                    f'{lattice_system} candidates carry {predicted.shape[1]} cell parameters '
                    f'against {len(partial_true)} in the sliced truth; the labeller would '
                    'compare different quantities.')
            correct, off_by_two = label_known_bl_batch(
                partial_true, predicted, lattice_system, rtol=rtol)
            is_correct[positions] = correct
            is_off_by_two[positions] = off_by_two
    result['is_correct'] = is_correct
    result['is_off_by_two'] = is_off_by_two
    return result


def _to_parquet(frame, path, row_group_size=None):
    try:
        import pyarrow as pa
        import pyarrow.parquet as pq
    except ImportError as error:
        raise ImportError(
            "Writing a benchmark pool needs pyarrow. Install it with 'pip install pyarrow'."
            ) from error
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    table = pa.Table.from_pandas(frame, preserve_index=False)
    pq.write_table(table, path, **({'row_group_size': row_group_size} if row_group_size else {}))
    return Path(path)


def part_dir(pool_dir, part):
    """Where one pool of processes writes its own stripe of an arm."""
    return Path(pool_dir) / PART_DIR / f'{int(part):03d}'


def write_candidate_shard(frame, directory, bundle, bravais_lattice):
    """One shard, in the name its reader rebuilds."""
    ordered = [name for name in CANDIDATE_COLUMNS if name in frame.columns]
    extra = [name for name in frame.columns if name not in CANDIDATE_COLUMNS]
    path = Path(directory) / f'candidates_{bundle}_{bravais_lattice}.parquet'
    return _to_parquet(frame[ordered + extra], path)


def write_entry_table(frame, directory):
    ordered = [name for name in ENTRY_COLUMNS if name in frame.columns]
    extra = [name for name in frame.columns if name not in ENTRY_COLUMNS]
    return _to_parquet(frame[ordered + extra], Path(directory) / ENTRY_TABLE_NAME)


def consolidate(pool_dir):
    """Stream every pool's stripe into one shard per (bundle, lattice), and one entry table.

    Streamed rather than concatenated: a triclinic shard of a full arm is millions of rows, and
    holding every stripe of it in memory to write it once is the one thing that does not fit.
    The stripes are removed only after their shard is written.
    """
    import pyarrow as pa
    import pyarrow.parquet as pq

    pool_dir = Path(pool_dir)
    parts = sorted(directory for directory in (pool_dir / PART_DIR).glob('*')
                   if directory.is_dir())
    if not parts:
        raise FileNotFoundError(f'No pool stripes under {pool_dir / PART_DIR}.')

    written = []
    names = sorted({path.name for part in parts for path in part.glob('*.parquet')})
    for name in names:
        sources = [part / name for part in parts if (part / name).is_file()]
        writer = None
        try:
            for source in sources:
                table = pq.read_table(source)
                if writer is None:
                    writer = pq.ParquetWriter(pool_dir / name, table.schema)
                writer.write_table(table.cast(writer.schema))
        finally:
            if writer is not None:
                writer.close()
        written.append(pool_dir / name)

    for part in parts:
        leftover = sorted(path.name for path in part.iterdir()
                          if path.suffix != '.parquet')
        if leftover:
            raise ValueError(
                f'{part} still holds {leftover} after its shards were consolidated. Anything a '
                'pool writes beside its shards has to be gathered before this point, or it is '
                'destroyed with the directory.')
        for path in part.glob('*.parquet'):
            path.unlink()
        part.rmdir()
    (pool_dir / PART_DIR).rmdir()
    return written


def write_manifest(pool_dir, **metadata):
    """Record what makes an arm regenerable, and what another arm must match to be paired.

    Every field in `IDENTITY_FIELDS` is required rather than optional: a manifest that omits one
    cannot be refused a pairing it should be refused, and the omission is invisible at the point
    it matters.
    """
    payload = dict(metadata)
    payload['schema_version'] = SCHEMA_VERSION
    payload['candidate_columns'] = list(CANDIDATE_COLUMNS)
    payload['entry_columns'] = list(ENTRY_COLUMNS)
    missing = [name for name in IDENTITY_FIELDS if name not in payload]
    if missing:
        raise ValueError(f'The manifest is missing {missing}, which pairing is decided on.')
    Path(pool_dir).mkdir(parents=True, exist_ok=True)
    path = Path(pool_dir) / MANIFEST_NAME
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(payload, handle, indent=2, sort_keys=True)
    return path


def stamp_complete(pool_dir, **metadata):
    """Mark an arm finished. Written last, by the process that consolidated it."""
    path = Path(pool_dir) / COMPLETION_NAME
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(dict(metadata), handle, indent=2, sort_keys=True)
    return path


def manifest_identity(manifests, allow=()):
    """Refuse to pair arms that differ in anything but the axis under study.

    `manifests` maps an arm name to its manifest. `allow` names the fields a comparison varies on
    purpose -- the search seed for a run-to-run floor, the pool size for a question about
    splitting a lattice across processes. Everything else in `IDENTITY_FIELDS` must match.

    This is what stops the two failures that look like measurements: an arm generated on one
    machine paired against an arm generated on another, and an arm generated before a change
    paired against one generated after it as though the change were the thing being varied.
    """
    names = list(manifests)
    if len(names) < 2:
        return True
    checked = [name for name in IDENTITY_FIELDS if name not in set(allow)]
    reference = manifests[names[0]]
    disagreements = []
    for name in names[1:]:
        for field in checked:
            left, right = reference.get(field), manifests[name].get(field)
            if left != right:
                disagreements.append(f'{field}: {names[0]}={left!r} vs {name}={right!r}')
    if disagreements:
        raise ValueError(
            'These arms are not comparable and pairing them would report the difference as a '
            'result:\n  ' + '\n  '.join(disagreements)
            + f'\nVarying one of these on purpose? Name it in allow=; currently {tuple(allow)}.')
    return True
